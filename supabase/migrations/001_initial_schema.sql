create extension if not exists pgcrypto;

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  display_name text not null default '',
  avatar_url text,
  bio text not null default '',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.talent_categories (
  id bigint generated by default as identity primary key,
  name text not null unique,
  slug text not null unique,
  is_active boolean not null default true,
  sort_order integer not null default 0
);

create table if not exists public.talents (
  id uuid primary key default gen_random_uuid(),
  owner_id uuid not null references public.profiles(id) on delete cascade,
  title text not null,
  description text not null default '',
  category_id bigint references public.talent_categories(id) on delete set null,
  cover_url text,
  status text not null default 'pending' check (status in ('pending','published','rejected','hidden')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.talent_media (
  id uuid primary key default gen_random_uuid(),
  talent_id uuid not null references public.talents(id) on delete cascade,
  owner_id uuid not null references public.profiles(id) on delete cascade,
  media_type text not null check (media_type in ('image','video')),
  file_url text not null,
  scan_status text not null default 'pending' check (scan_status in ('pending','approved','rejected','manual_review')),
  created_at timestamptz not null default now()
);

create table if not exists public.talent_follows (
  follower_id uuid not null references public.profiles(id) on delete cascade,
  talent_owner_id uuid not null references public.profiles(id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (follower_id, talent_owner_id),
  check (follower_id <> talent_owner_id)
);

create table if not exists public.talent_likes (
  user_id uuid not null references public.profiles(id) on delete cascade,
  talent_id uuid not null references public.talents(id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (user_id, talent_id)
);

create table if not exists public.talent_comments (
  id uuid primary key default gen_random_uuid(),
  talent_id uuid not null references public.talents(id) on delete cascade,
  user_id uuid not null references public.profiles(id) on delete cascade,
  body text not null check (char_length(body) between 1 and 1000),
  status text not null default 'pending' check (status in ('pending','published','hidden')),
  created_at timestamptz not null default now()
);

create table if not exists public.talent_reports (
  id uuid primary key default gen_random_uuid(),
  talent_id uuid references public.talents(id) on delete cascade,
  media_id uuid references public.talent_media(id) on delete cascade,
  reporter_id uuid references public.profiles(id) on delete set null,
  reason text not null,
  details text not null default '',
  status text not null default 'open' check (status in ('open','reviewing','resolved','dismissed')),
  created_at timestamptz not null default now(),
  check (talent_id is not null or media_id is not null)
);

create index if not exists talents_owner_id_idx on public.talents(owner_id);
create index if not exists talents_category_id_idx on public.talents(category_id);
create index if not exists talents_status_created_idx on public.talents(status, created_at desc);
create index if not exists talent_media_talent_id_idx on public.talent_media(talent_id);
create index if not exists talent_comments_talent_status_idx on public.talent_comments(talent_id, status);

